#!/usr/bin/env python3
"""Generates the default emblems, extra emblems and unlockables of a game
that keeps them in its code (m_cond.c), not in SOC:

    python3 tools/gen_progress_defaults.py legacy path/to/m_cond.c > lib/services/legacy_progress_data.dart
    python3 tools/gen_progress_defaults.py kart path/to/m_cond.c > lib/services/kart_progress_data.dart

SRB2 Legacy (2.1): https://github.com/srb2-preservation/srb2-legacy (src/m_cond.c)
SRB2Kart: https://github.com/STJr/Kart-Public (src/m_cond.c)
"""
import re
import sys

prefix = sys.argv[1]
source = {'legacy': 'SRB2 Legacy src/m_cond.c (srb2-preservation/srb2-legacy, GPL-2.0)',
          'kart': 'SRB2Kart src/m_cond.c (STJr/Kart-Public, GPL-2.0)'}[prefix]
src = open(sys.argv[2], encoding='latin-1').read()
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
src = re.sub(r'//[^\n]*', '', src)


def array(name):
    m = re.search(name + r'\s*\[[A-Z_]+\]\s*=\s*\{', src)
    i = m.end()
    depth, out, cur = 1, [], None
    while depth:
        c = src[i]
        if c == '"':
            j = i + 1
            while src[j] != '"':
                j += 2 if src[j] == '\\' else 1
            if cur is not None:
                cur += src[i:j + 1]
            i = j + 1
            continue
        if c == '{':
            depth += 1
            if depth == 2:
                cur = ''
                i += 1
                continue
        elif c == '}':
            depth -= 1
            if depth == 1:
                out.append(fields(cur))
                cur = None
                i += 1
                continue
        if cur is not None:
            cur += c
        i += 1
    return out


def fields(body):
    out, buf, i = [], '', 0
    strs = []
    while i < len(body):
        c = body[i]
        if c == '"':
            j = i + 1
            while body[j] != '"':
                j += 2 if body[j] == '\\' else 1
            strs.append(body[i + 1:j])
            buf += '\0'
            i = j + 1
            continue
        if c == ',':
            out.append(buf)
            buf = ''
        else:
            buf += c
        i += 1
    out.append(buf)
    res = []
    for f in out:
        f = f.strip()
        if '\0' in f:
            n = f.count('\0')
            s = ''.join(strs[:n])
            del strs[:n]
            res.append(('str', s.encode().decode('unicode_escape')))
        elif f:
            res.append(('raw', f))
    return res


def dart(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('\n', '\\n').replace('$', '\\$') + "'"


def raw(f):
    return f[1]


types = {'0': 'global', 'ET_GLOBAL': 'global', 'ET_SKIN': 'skin', 'ET_SCORE': 'score', 'ET_TIME': 'time',
         'ET_RINGS': 'rings', 'ET_NGRADE': 'nightsGrade', 'ET_NTIME': 'nightsTime'}

print(f'// GENERATED by tools/gen_progress_defaults.py from {source}.')
print('// Do not edit by hand.')
print('//')
print('// The game keeps its emblems, extra emblems and unlockables in its code;')
print('// addons replace them with SOC (Emblem N, ExtraEmblem N, Unlockable N).')
print()
print("import 'game_progress.dart';")
print()
print('/// Emblems: type, map, sprite, color, var (target), hint.')
print(f'const {prefix}Emblems = <(EmblemType, int, String, String, String, String)>[')
for e in array('emblemlocations'):
    t, _x, _y, _z, level, sprite, color, var, hint = e[:9]
    sp = raw(sprite).strip("'")
    print(f"  (EmblemType.{types[raw(t)]}, {raw(level)}, {dart(sp)}, {dart(raw(color))}, {dart(raw(var))}, {dart(hint[1])}),")
print('];')
print()
print('/// Extra emblems: name, objective, condition set, sprite, color.')
print(f'const {prefix}ExtraEmblems = <(String, String, int, String, String)>[')
for e in array('extraemblems'):
    name, desc, cond, sprite, color = e[:5]
    print(f"  ({dart(name[1])}, {dart(desc[1])}, {raw(cond)}, {dart(raw(sprite).strip(chr(39)))}, {dart(raw(color))}),")
print('];')
print()
print('/// Unlockables: name, objective, condition set, type (Header: a menu')
print('/// header, not a secret), no checklist.')
print(f'const {prefix}Unlockables = <(String, String, int, String, bool)>[')
for e in array('unlockables'):
    name, obj, _h, cond, t, _v, _nc, nochk = e[:8]
    kind = 'Header' if raw(t) == 'SECRET_HEADER' else ''
    print(f"  ({dart(name[1])}, {dart(obj[1])}, {raw(cond)}, {dart(kind)}, {raw(nochk)}),")
print('];')
